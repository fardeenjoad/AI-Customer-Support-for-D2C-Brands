export type IconName = keyof typeof iconMap;

export interface IconProps {
  name: IconName;
  className?: string;
  size?: number | string;
}

export function Icon({ name, className, size = 16 }: IconProps) {
  const LucideIcon = iconMap[name] as React.ComponentType<{ className?: string; size?: number | string }>;
  if (!LucideIcon) return null;
  return <LucideIcon className={cn("shrink-0", className)} size={size} />;
}
